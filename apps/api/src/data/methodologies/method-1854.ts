export const scoringConfig: ConfigurableScoring = {
  min: 1,
  max: 6,
  scales: [
    ...scaleDefinitions.map(([key, label], index) => ({
      key,
      label,
      items: scaleItems(index),
      reverseItems: [] as number[],
      aggregation: 'formula' as const,
      formula: 'sum(response in {4,5,6})',
    })),
    {
      key: 'overall_self_realization',
      label: 'Общий уровень самореализации',
      items,
      reverseItems: [],
      aggregation: 'formula',
      formula: 'sum(scales 1,3,5,7,11,13) + mean(scales 9,10) - sum(scales 2,4,6,8,12,14) - mean(scales 15,16); scale 17 excluded',
    },
    ...[
      ['personal_self_realization', 'Личностная самореализация', 0],
      ['social_self_realization', 'Социальная самореализация', 2],
      ['professional_self_realization', 'Профессиональная самореализация', 4],
    ].map(([key, label, firstScale]) => {
      const blockScales = Array.from({ length: 2 }, (_, block) => Array.from({ length: 17 }, (_, scale) => scaleItems(scale)[firstScale as number] + block * 34));
      return {
        key: key as string,
        label: label as string,
        items: Array.from({ length: 34 }, (_, index) => (firstScale as number) * 17 + index + 1),
        reverseItems: [],
        aggregation: 'formula' as const,
        formula: `signed positive and negative scale aggregation over ${blockScales.flat().join(',')}; sincerity excluded`,
      };
    }),
  ],
};

