const scaleForRole = (role: keyof typeof roleKeyByName) => ({
  key: role,
  label: { manager: 'Управленец', organizer: 'Организатор', administrator: 'Администратор', leader: 'Руководитель' }[role],
  items: [1, 2, 3, 4, 5, 6, 7, 8, 9],
  reverseItems: [],
  aggregation: 'sum' as const,
  itemScores: Object.fromEntries(roleKeyByName[role].map((correctOption, index) => [
    index + 1,
    Object.fromEntries([1, 2, 3, 4].map(option => [String(option), option === correctOption ? option : 0])),
  ])),
});

