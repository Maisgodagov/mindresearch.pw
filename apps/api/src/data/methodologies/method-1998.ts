export const scoringConfig: ConfigurableScoring = {
  min: 0,
  max: 1,
  scales: blocks.map((block, blockIndex) => {
    const first = blockIndex * 20 + 1;
    return {
      key: ['phlegmatic', 'melancholic', 'choleric', 'sanguine'][blockIndex],
      label: block.label,
      items: Array.from({ length: 20 }, (_, index) => first + index),
      reverseItems: [],
      aggregation: 'count-option',
      optionValue: '1',
    };
  }),
};

