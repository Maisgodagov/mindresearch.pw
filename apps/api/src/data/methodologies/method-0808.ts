export const scoringConfig: ConfigurableScoring = {
  min: 1,
  max: 7,
  scales: styles.map((label, styleIndex) => ({
    key: `style_${styleIndex + 1}`,
    label,
    items: keyLetters.map((row, sectionIndex) => sectionIndex * 7 + letterIndex[row[styleIndex]] + 1),
    reverseItems: [],
    aggregation: 'sum' as const,
  })),
};

const rankPermutation = [1, 2, 3, 4, 5, 6, 7];
const rankAnswers = Object.fromEntries(allItemNumbers.map((item) => {
  const section = Math.floor((item - 1) / 7);
  const choiceIndex = (item - 1) % 7;
  return [String(item), rankPermutation[(choiceIndex + section) % 7]];
}));
// For each key cell, expected answer rank comes from the corresponding choice in its section.
const expectedFor = (answers: Record<string, number>) => Object.fromEntries(scoringConfig.scales.map((scale) => [
  scale.key,
  scale.items.reduce((sum, item) => sum + answers[String(item)], 0),
]));
const validationCases: ValidationCase[] = [
  {
    title: 'Ручная сверка ключа: в каждом разделе ответы А–Ж ранжированы от 1 до 7 циклическим сдвигом',
    answers: rankAnswers,
    expected: expectedFor(rankAnswers as Record<string, number>),
  },
];

