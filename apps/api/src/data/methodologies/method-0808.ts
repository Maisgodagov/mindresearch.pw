// Each row maps style columns 1..7 to choice letters А..Ж in that section.
const keyLetters = [
  ['Б', 'Д', 'Ж', 'Г', 'В', 'А', 'Е'],
  ['Г', 'Б', 'Д', 'В', 'А', 'Ж', 'Е'],
  ['Ж', 'Е', 'Б', 'Г', 'В', 'Д', 'А'],
  ['Д', 'А', 'Ж', 'Б', 'В', 'Г', 'Е'],
];

const letterIndex: Record<string, number> = { А: 0, Б: 1, В: 2, Г: 3, Д: 4, Е: 5, Ж: 6 };
const allItemNumbers = Array.from({ length: 28 }, (_, index) => index + 1);

const questions: SeedSection['questions'] = sections.flatMap((section, sectionIndex) =>
  section.choices.map((choice, choiceIndex) => {
    const sectionNumber = sectionIndex + 1;
    const questionNumber = sectionIndex * 7 + choiceIndex + 1;
    return {
      code: `test_838_${questionNumber}`,
      text: `${section.title}\n${['А', 'Б', 'В', 'Г', 'Д', 'Е', 'Ж'][choiceIndex]} — ${choice}`,
      type: 'single' as const,
      required: true,
      options: Array.from({ length: 7 }, (_, rank) => ({ value: String(rank + 1), label: String(rank + 1) })),
      validation: { section: sectionNumber, uniqueValuesWithinSection: true },
    };
  }),
);

