const itemNumbers = Array.from({ length: 40 }, (_, index) => index + 1);
const groups = [
  { key: 'basic', label: 'Базовые коммуникативные трудности', items: itemNumbers.slice(0, 10) },
  { key: 'content', label: 'Содержательные коммуникативные трудности', items: itemNumbers.slice(10, 20) },
  { key: 'instrumental', label: 'Инструментальные коммуникативные трудности', items: itemNumbers.slice(20, 30) },
  { key: 'reflective', label: 'Рефлексивные коммуникативные трудности', items: itemNumbers.slice(30, 40) },
];

const scoringConfig: ConfigurableScoring = {
  min: 0,
  max: 4,
  scales: groups.flatMap((group) =>
    (['peers', 'adults'] as const).map((context) => ({
      key: `${group.key}_${context}`,
      label: `${group.label}: ${context === 'peers' ? 'общение со сверстниками' : 'общение со взрослыми'}`,
      items: group.items.map((item) => (item - 1) * 2 + (context === 'peers' ? 1 : 2)),
      reverseItems: [],
      aggregation: 'sum' as const,
    })),
  ),
};

