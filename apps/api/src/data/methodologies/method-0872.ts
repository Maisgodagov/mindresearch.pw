const makeScale = (key: string, label: string, yes: number[], no: number[]) => {
  const itemIds = [...yes, ...no].sort((a, b) => a - b);
  // A keyed Yes earns 1; a keyed No earns 1 when the answer is 0.
  // The offset +1 per keyed No plus signed binary response equals hit count.
  const offset = no.length;
  const weights = Object.fromEntries(itemIds.map(item => [item, yes.includes(item) ? 1 : -1]));
  return {
    key,
    label,
    items: itemIds,
    reverseItems: [] as number[],
    weights: Object.fromEntries(itemIds.map(item => [item, weights[item] + offset / itemIds.length])),
    aggregation: 'sum' as const,
  };
};

