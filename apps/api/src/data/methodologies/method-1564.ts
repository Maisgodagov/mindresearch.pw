const responseValues = ['true', 'probably_true', 'probably_false', 'false'];
export const scoringConfig: ConfigurableScoring = {
  min: 0,
  max: 1,
  scales: scaleKeys.map(scale => {
    const keyed = new Map<number, boolean>();
    scale.trueItems.forEach(item => keyed.set(item, true));
    scale.falseItems.forEach(item => keyed.set(item, false));
    const items = [...keyed.keys()].sort((a, b) => a - b);
    return {
      key: scale.key,
      label: scale.label,
      items,
      reverseItems: scale.falseItems,
      aggregation: 'sum' as const,
      itemScores: Object.fromEntries(items.map(item => [item, Object.fromEntries(responseValues.map(value => [value, (value === 'true' || value === 'probably_true') === keyed.get(item) ? 1 : 0]))])),
    };
  }),
};

