const scaleItems = {
  psychosomatic: [1, 4, 7, 10, 13, 16, 19],
  neurotic: [2, 5, 8, 11, 14, 17, 20],
  authoritarian: [3, 6, 9, 12, 15, 18, 21],
};

export const scoringConfig: ConfigurableScoring = {
  min: 0,
  max: 1,
  scales: [
    ...Object.entries(scaleItems).map(([key, items]) => ({
      key,
      label: key === 'psychosomatic' ? 'Психосоматический тип' : key === 'neurotic' ? 'Невротичный тип' : 'Авторитарный тип',
      items,
      reverseItems: [],
      aggregation: 'sum' as const,
      itemScores: Object.fromEntries(items.map((item) => [item, { yes: 1, no: 0 }])),
    })),
  ],
};

