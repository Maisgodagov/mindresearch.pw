const scoresFor = (answers: Record<string, number>) => Object.fromEntries(scoringConfig.scales.map(scale => {
  const values = scale.items.map(item => {
    const value = answers[String(item)];
    return scale.reverseItems.includes(item) ? 8 - value : value;
  });
  return [scale.key, values.reduce((sum, value) => sum + value, 0) / values.length];
}));

