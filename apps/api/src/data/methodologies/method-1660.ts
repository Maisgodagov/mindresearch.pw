  const yesItems = [...scoringKey.yes];
  const noItems = [...scoringKey.no];
  const itemScores = Object.fromEntries([...yesItems.map(item => [item, { yes: 1, yes_maybe: 1, no_maybe: 0, no: 0 }]), ...noItems.map(item => [item, { yes: 0, yes_maybe: 0, no_maybe: 1, no: 1 }])]);
