const itemWeights: Record<number, Record<string, number>> = Object.fromEntries(
  items.map((_, index) => {
    const item = index + 1;
    const yesWeight = [5, 9, 16].includes(item) ? 1
      : [2, 3, 10, 11, 12, 13, 14, 15, 17, 18, 21, 22, 23, 24].includes(item) ? 2
      : [8, 19, 20].includes(item) ? 5
      : 0;
    const reverse = [1, 4, 6, 7].includes(item);
    return [item, { yes: reverse ? 0 : yesWeight, no: reverse ? 2 : 0 }];
  }),
);

