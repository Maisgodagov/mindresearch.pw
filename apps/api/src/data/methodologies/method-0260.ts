const scoringConfig: ConfigurableScoring = {
  min: 1, max: 2,
  scales: (Object.keys(scaleItems) as (keyof typeof scaleItems)[]).map(key => ({
    key, label: labels[key], items: scaleItems[key], reverseItems: [], aggregation: 'sum',
  })),
};

const keyItem: Record<number, { scale: keyof typeof scaleItems; value: number }> = {};
for (const key of Object.keys(scaleItems) as (keyof typeof scaleItems)[]) {
  scaleItems[key].forEach((item, index) => {
    keyItem[item] = { scale: key, value: choiceLetters[key][index] };
  });
}
// Hand-checked against the published key: one point for each selection matching its column.
const expected: Record<string, number> = Object.fromEntries(Object.keys(scaleItems).map(key => [key, 0]));
const answers: Record<string, number> = {};
choices.forEach((_, index) => {
  const item = index + 1;
  const keyed = keyItem[item];
  if (!keyed) throw new Error(`Missing DDO key for item ${item}`);
  answers[String(item)] = keyed.value;
  expected[keyed.scale] += 1;
});
const validationCases: ValidationCase[] = [{
  title: 'Ручная проверка: все ответы соответствуют ключу; получено по одному баллу за каждый пункт шкалы',
  answers, expected,
}];

