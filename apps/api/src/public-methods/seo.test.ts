import { afterEach, describe, expect, it } from "vitest";
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { initialCatalog } from "./model.js";
import { publicDocument, injectDocument } from "./render.js";
import { publicSeo, publicStructuredData } from "./seo.js";
import { createPublicPagesSync, methodsSitemap } from "./static-pages.js";
import { memoryRepository } from "./testing.js";
let directory: string | undefined;
afterEach(async () => { if(directory) { await rm(directory, {recursive:true, force:true}); directory=undefined; } });
const template = '<html><head><title>Old</title><meta name="description" content="Old"><meta property="og:title" content="Old"><link rel="canonical" href="https://old.example/"></head><body><div id="root"></div><script src="/assets/app.js"></script></body></html>';
describe("public test SEO", () => {
  it("keeps article metadata, citations, breadcrumb and internal links consistent", () => {
    const method = initialCatalog[0];
    const seo = publicSeo(method);
    const html = injectDocument(template, publicDocument(initialCatalog, method));
    expect(html.match(/rel="canonical"/g)).toHaveLength(1);
    expect(html.match(/property="og:title"/g)).toHaveLength(1);
    expect(html.match(/<h1>/g)).toHaveLength(1);
    expect(html).toContain(`href="${seo.url}"`);
    expect(seo.url).toBe("https://mindresearch.pro/methods/rosenberg-self-esteem/");
    expect(html).toContain('name="twitter:card" content="summary_large_image"');
    expect(html).toContain('content="1200"');
    expect(html).toContain(method.sources[0].url);
    expect(html).toContain('/methods/general-self-efficacy/');
    const graph = publicStructuredData(initialCatalog, method)["@graph"];
    expect(graph.some(item => item["@type"] === "BreadcrumbList")).toBe(true);
    const list = publicStructuredData(initialCatalog)["@graph"].find(item => item["@type"] === "CollectionPage") as any;
    expect(list.mainEntity.itemListElement).toHaveLength(3);
    expect(JSON.stringify(graph)).not.toMatch(/AggregateRating|MedicalTest/);
  });
  it("supports editorial snippets without changing scoring fields", () => {
    const seo = publicSeo({...initialCatalog[0],seoTitle:"Авторский заголовок",seoDescription:"Авторское описание"});
    expect(seo.title).toBe("Авторский заголовок");
    expect(seo.description).toBe("Авторское описание");
  });
  it("exports published HTML, updates it on publish, ignores drafts and withdraws pages", async () => {
    directory=await mkdtemp(join(tmpdir(),"mindresearch-seo-"));
    await writeFile(join(directory,"index.html"),template);
    const repository=memoryRepository();
    const sync=createPublicPagesSync(repository,directory);
    await sync();
    const method=initialCatalog[0];
    const path=join(directory,"methods",method.slug,"index.html");
    const initial=await readFile(path,"utf8");
    expect(initial).toContain(method.intro);
    const publication=(await repository.publications()).find(item=>item.slug===method.slug)!;
    const changed={...publication.draft,intro:"Новая проверенная редакция статьи"};
    await repository.savePublication(method.slug,changed,"draft",publication.revision);
    await sync();
    expect(await readFile(path,"utf8")).toBe(initial);
    await repository.savePublication(method.slug,changed,"publish",publication.revision+1);
    await sync();
    expect(await readFile(path,"utf8")).toContain(changed.intro);
    const privateHtml=await readFile(join(directory,"assessment/result/index.html"),"utf8");
    expect(privateHtml).toContain('content="noindex,nofollow"');
    expect(privateHtml).not.toContain(method.intro);
    const start=await readFile(join(directory,"methods",method.slug,"start/index.html"),"utf8");
    expect(start).toContain('content="noindex,nofollow"');
    await repository.savePublication(method.slug,changed,"unpublish",publication.revision+2);
    await sync();
    expect(await readFile(path,"utf8")).not.toContain(method.intro);
    expect(await readFile(path,"utf8")).toContain('content="noindex,nofollow"');
    const sitemap=await readFile(join(directory,"sitemap.xml"),"utf8");
    expect(sitemap).not.toContain(`/methods/${method.slug}/`);
    expect(sitemap).not.toMatch(/assessment|start|lastmod/);
    expect(sitemap).toContain('/methods/general-self-efficacy/');
  });
  it("uses only real publication timestamps for lastmod", async () => {
    const publications=await memoryRepository().publications();
    publications[0].publishedAt="2026-10-21T10:00:00.000Z";
    const sitemap=methodsSitemap(publications);
    expect(sitemap).toContain('<lastmod>2026-10-21T10:00:00.000Z</lastmod>');
    expect(sitemap.match(/<lastmod>/g)).toHaveLength(1);
  });
});
