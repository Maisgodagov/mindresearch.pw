const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({channel:'msedge'});
try{for(const width of [1440,390]){
 const context=await browser.newContext({viewport:{width,height:900}});const page=await context.newPage();
 let saves=0;
 await page.goto('http://127.0.0.1:5181/methods/rosenberg-self-esteem/start/');
 await page.getByRole('button',{name:'Отказаться',exact:true}).click();
 await page.locator('.pm-consent input').check();await page.getByRole('button',{name:'Начать',exact:true}).click();
 await page.locator('.respondent-option').first().waitFor();
 assert.equal(await page.locator('.public-assessment-respondent').count(),1);
 assert.equal(await page.locator('.td-contents, .pm-question-controls').count(),0);
 let release,markStarted;const paused=new Promise(resolve=>release=resolve);const started=new Promise(resolve=>markStarted=resolve);
 await page.route('**/api/public/assessments/*/save',async route=>{saves++;markStarted();await paused;await route.continue();});
 await page.locator('.respondent-option').first().click();
 await started;
 assert.equal(await page.locator('.respondent-option').first().getAttribute('aria-pressed'),'true');
 const selected=await page.locator('.respondent-option').first().evaluate(el=>getComputedStyle(el).backgroundColor);
 const other=await page.locator('.respondent-option').nth(1).evaluate(el=>getComputedStyle(el).backgroundColor);
 assert.notEqual(selected,other,'Selected answer must have a distinct background');
 await page.locator('.respondent-option').nth(1).click();assert.equal(saves,1,'Rapid second click must not create another save');
 assert.equal(await page.getByText('Вопрос 1 из 10',{exact:true}).count(),1,'Do not advance before save succeeds');
 release();await page.getByText('Вопрос 2 из 10',{exact:true}).waitFor();await page.unroute('**/api/public/assessments/*/save');
 assert.equal(await page.getByRole('button',{name:'Далее',exact:true}).count(),0);
 await page.getByRole('button',{name:'Назад',exact:true}).click();await page.getByText('Вопрос 1 из 10',{exact:true}).waitFor();
 assert.equal(await page.locator('.respondent-option').first().getAttribute('aria-pressed'),'true');
 await page.locator('.respondent-option').nth(1).click();await page.getByText('Вопрос 2 из 10',{exact:true}).waitFor();
 await page.reload();await page.getByText('Вопрос 2 из 10',{exact:true}).waitFor();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 console.log(`PASS ${width}: shared UI, selected feedback, save-before-advance, double-click guard, back/edit, reload`);
 await context.close();
}}finally{await browser.close();}})().catch(error=>{console.error(error);process.exitCode=1});
